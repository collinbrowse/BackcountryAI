// MARK: - A card as a source

extension FieldCard {
    /// The headings the card is read under: first aid is recognized, treated and evacuated; a stuck truck isn't.
    var headings: (recognize: String, treat: String, avoid: String, evacuate: String) {
        area == .medical ? ("Recognize", "Treat", "Don't", "Evacuate if") : ("Know", "Do", "Don't", "Get help if")
    }

    /// The card as plain text for the answer model: its first source when a question is about this situation.
    var promptText: String {
        var lines: [String] = []
        if !recognize.isEmpty { lines.append("\(headings.recognize): " + recognize.joined(separator: " ")) }
        if !treat.isEmpty {
            lines.append("\(headings.treat):")
            lines += treat.enumerated().map { "\($0.offset + 1). \($0.element)" }
        }
        if !avoid.isEmpty { lines.append("\(headings.avoid): " + avoid.joined(separator: " ")) }
        if !evacuateIf.isEmpty { lines.append("\(headings.evacuate): " + evacuateIf.joined(separator: " ")) }
        return lines.joined(separator: "\n")
    }

    /// The card as an article, for reading it from an answer's sources (ArticleView reads Markdown).
    var articleBody: String {
        var parts: [String] = []
        func section(_ heading: String, _ items: [String], numbered: Bool = false) {
            guard !items.isEmpty else { return }
            parts.append("## \(heading)")
            parts.append(items.enumerated().map { numbered ? "\($0.offset + 1). \($0.element)" : "- \($0.element)" }
                .joined(separator: "\n"))
        }
        section(headings.recognize, recognize)
        section(headings.treat, treat, numbered: true)
        section(headings.avoid, avoid)
        section(headings.evacuate, evacuateIf)
        parts.append(Self.disclaimer)
        return parts.joined(separator: "\n\n")
    }

    static let disclaimer = "General guidance written for this app. It is not a substitute for training such as a "
        + "WFR course. If you can reach help (911, or SOS by satellite), do."

    /// What cards are called as a source, in the prompt and under an answer.
    static let sourceLabel = "Scout field card"
    static let sourceKey = "field-card"
    /// Doc and passage ids of cards start here: above the library's and the person's own documents' (Library.mineIDBase).
    static let idBase: Int64 = 1 << 41

    /// This card as a search hit, so it sits among an answer's sources like any library passage.
    var passage: Passage {
        let n = Self.idBase + Int64(Self.all.firstIndex { $0.id == id } ?? 0)
        return Passage(id: n, docID: n, title: title, source: Self.sourceLabel, sourceKey: Self.sourceKey,
                       official: false, text: promptText, coverage: nil)
    }

    /// The card behind a passage or doc id, if it is one.
    static func card(passageID n: Int64) -> FieldCard? {
        let i = Int(n - idBase)
        return n >= idBase && all.indices.contains(i) ? all[i] : nil
    }
}
