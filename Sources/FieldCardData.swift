import Foundation

/// Quick reference cards: what to do in the situations people most often ask about, short enough to read at a
/// glance and written for this app. They work with no AI (Field mode and the Guide show them as they are), and
/// when a question in chat is about a card's situation the card is the answer model's first source (CardMatcher,
/// Retrieval.find): with a card as its source, the model's answers to first-aid questions it otherwise got wrong
/// were right.
///
/// The first-aid cards are general wilderness first-aid guidance. The situation cards were drafted from the
/// library's public-domain sources (National Park Service, National Weather Service, CDC, U.S. Army and Air Force
/// manuals); docs/field-cards.md lists each card's sources and what is still unsure. All of them must be reviewed
/// by qualified people (a wilderness medicine instructor; for the vehicle, stove and dog cards, a mechanic and a
/// vet) before release.
struct FieldCard: Identifiable, Hashable, Sendable {
    enum Area: String, Sendable { case medical, survival, weather, water, wildlife, vehicle, gear, pets }

    let id: String
    let title: String
    let area: Area
    /// How to recognize or size up the situation.
    let recognize: [String]
    /// What to do, in order.
    let treat: [String]
    /// Common mistakes, each starting "Don't".
    var avoid: [String] = []
    /// When to call for rescue or evacuate.
    let evacuateIf: [String]
    /// Library searches for the source material.
    let searches: [String]
    /// Ways people describe this situation, in their own words. A question is matched to a card by how close it
    /// is to one of these (CardMatcher), so they are written the way people type or dictate, not as titles.
    let asks: [String]
    /// Questions that share the card's words but need a different answer; a question closer to one of these than
    /// to any of `asks` doesn't get the card.
    let notAsks: [String]
}

extension FieldCard {
    /// Every card, for matching questions in chat.
    static let all: [FieldCard] = firstAid + situations

    static func card(id: String) -> FieldCard? { all.first { $0.id == id } }

